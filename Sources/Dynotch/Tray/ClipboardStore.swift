import AppKit
import Combine
import SwiftUI

/// Text that's been copied, for the Tray's Clipboard side and `clip` in the command field. Off until
/// asked for. macOS doesn't say when something's copied, so `look` compares the clipboard's change
/// count, and only reads when that moved: from the pointer monitor that already runs, on app
/// switches, and on a slow poll. Unpinned clips live in memory and are gone when Dynotch quits. Pins,
/// which the user chose to keep, are all that reaches the disk. Clip text never goes in a log, a
/// notice or the recent list, and nothing leaves the Mac.
@MainActor
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()

    struct Clip: Identifiable, Equatable {
        enum Kind: Equatable {
            case text
            /// A command or some code, set in monospace.
            case code
            /// A lone hex color, and what fills its swatch.
            case color(red: Double, green: Double, blue: Double, opacity: Double)
            /// A lone web link.
            case link(URL)
        }

        let id: UUID
        let text: String
        /// When it was last copied, which sets its place on the shelf.
        var copiedAt: Date
        /// Stays through Clear, turning the history off and quitting, and doesn't count toward the 50.
        var isPinned: Bool
        // Worked out once: a clip can run to 100,000 characters, and views ask on every update.
        let kind: Kind
        /// The first line, cut short.
        let title: String
        /// As much as any card has room for.
        let preview: String

        init(id: UUID = UUID(), text: String, copiedAt: Date = .now, isPinned: Bool = false) {
            self.id = id
            self.text = text
            self.copiedAt = copiedAt
            self.isPinned = isPinned
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            kind = Self.kind(of: trimmed)
            title = Self.firstLine(of: trimmed)
            preview = String(trimmed.prefix(400))
        }
    }

    /// What macOS lets Dynotch do with the clipboard.
    enum Access: Equatable {
        /// It reads, or it will, and macOS may ask the first time.
        case allowed
        /// macOS would put up an alert for every read, so Dynotch doesn't.
        case asks
        /// Turned off for Dynotch in System Settings.
        case denied
        /// A read came back empty, though there was text to read. Only that copy is given up on.
        case refused
    }

    /// What the store asks macOS. A test swaps these to count what's asked and to act out what only
    /// macOS can do: a named pasteboard always allows reading.
    struct System {
        var changeCount: @MainActor (NSPasteboard) -> Int = { $0.changeCount }
        var access: @MainActor (NSPasteboard) -> Access = { Access(of: $0) }
        var read: @MainActor (NSPasteboard) -> String? = { $0.string(forType: .string) }
        var frontApp: @MainActor () -> String? = { NSWorkspace.shared.frontmostApplication?.bundleIdentifier }
    }

    /// How many clips are kept, pins aside.
    static let limit = 50
    /// The longest clip, in UTF-16 units, since a `String`'s own count walks all of it, however long.
    static let longest = 100_000

    /// Left alone from these types alone, before any content is read. The first eight are how apps
    /// mark a secret or a passing thing. Reading Universal Clipboard blocks until the other device
    /// hands it over, and it comes from no app that can be checked.
    static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"), .init("net.antelle.keeweb"),
        .init("de.petermaurer.TransientPasteboardType"), .init("Pasteboard generator type"),
        .init("com.typeit4me.clipping"), .init("com.apple.is-remote-clipboard"),
    ]

    /// How password managers' bundle IDs start, in lowercase, so betas and App Store editions count.
    /// Copies made with one of these in front are left out, whatever their types say.
    static let passwordManagers = [
        "com.1password.", // 1Password 8
        "com.agilebits.onepassword", // 1Password 4 to 7, from the web and the App Store
        "com.bitwarden.",
        "com.lastpass.",
        "com.dashlane.",
        "org.keepassxc.", "org.keepassx.",
        "com.keepersecurity.", "com.callpod.keepermac", // Keeper, from the web and the App Store
        "in.sinew.enpass",
        "com.nordsec.nordpass",
        "me.proton.pass",
        "com.apple.passwords", // The app and its menu bar extra
        "com.apple.keychainaccess",
    ]

    /// Pinned first, then newest.
    @Published private(set) var clips: [Clip] = []
    @Published private(set) var access = Access.allowed

    private let support: URL
    private let fileURL: URL
    private let pasteboard: NSPasteboard
    private let energy: EnergyCoordinator
    private let cadence: Cadence
    private let system: System
    private var isWatching = false
    /// The change count `look` last dealt with.
    private var seenCount = 0
    private var lastPointerLook = Date.distantPast
    /// The app in front. While nobody's looking `look` doesn't run, so any app that came to the front
    /// meanwhile is here too, and a copy found afterwards may have come from any of them.
    private var frontApps: [String?] = []
    private var poll: Poll?
    private var switchObserver: NSObjectProtocol?
    private var cancellables = Set<AnyCancellable>()

    private convenience init() {
        self.init(support: FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Dynotch", isDirectory: true), pasteboard: .dynotch, energy: .shared)
    }

    /// `support` holds `clipboard.json`. The tests pass a folder, a named pasteboard and a coordinator
    /// of their own.
    init(support: URL, pasteboard: NSPasteboard, energy: EnergyCoordinator, cadence: Cadence = .clipboard,
         system: System = System()) {
        self.support = support
        fileURL = support.appendingPathComponent("clipboard.json")
        self.pasteboard = pasteboard
        self.energy = energy
        self.cadence = cadence
        self.system = system
    }

    /// Loads the pins and follows the setting, which is sent as it's set and once now.
    func start() {
        load()
        AppSettings.shared.$clipboardHistory
            .sink { [weak self] isOn in self?.setWatching(isOn) }
            .store(in: &cancellables)
    }

    /// Turning on and launching take the change count as it is, unread: what's on the clipboard by
    /// then came from nobody knows where. Turning off forgets everything but the pins at once.
    func setWatching(_ on: Bool) {
        guard on != isWatching else { return }
        isWatching = on
        if on {
            seenCount = system.changeCount(pasteboard)
            frontApps = [system.frontApp()]
            // A refusal from an earlier run shows now, rather than after the next copy.
            access = system.access(pasteboard)
            poll = energy.schedule(cadence) { [weak self] in self?.look() }
            switchObserver = NSWorkspace.shared.notificationCenter.addObserver(
                forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main) { [weak self] notification in
                let app = notification.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
                let bundleID = app?.bundleIdentifier
                MainActor.assumeIsolated { self?.appDidActivate(bundleID) }
            }
        } else {
            poll?.cancel()
            poll = nil
            if let switchObserver { NSWorkspace.shared.notificationCenter.removeObserver(switchObserver) }
            switchObserver = nil
            access = .allowed
            clear()
        }
    }

    // MARK: Looking

    /// The pointer moved, which `NotchManager` says on every mouse event. Off, this is one flag and
    /// the clock isn't even read; on, it's a time comparison until the second is up.
    func sawInput(now: @autoclosure () -> Date = .now) {
        guard isWatching else { return }
        let now = now()
        guard now.timeIntervalSince(lastPointerLook) >= 1 else { return }
        lastPointerLook = now
        look()
    }

    /// Reads the clipboard if its change count moved, and keeps what's there if it may. Each change
    /// is dealt with once, so what's skipped or refused isn't tried again.
    func look() {
        guard isWatching, !energy.isQuiet else { return }
        let sources = frontApps
        frontApps = Array(frontApps.suffix(1))
        let count = system.changeCount(pasteboard)
        guard count != seenCount else {
            // The user may have just sorted this out in System Settings. Nothing has changed to read yet.
            if access == .asks || access == .denied { access = system.access(pasteboard) }
            return
        }
        seenCount = count
        access = keepCopy(count, from: sources)
    }

    /// The new app is in front by now, so a copy this finds came from the one that just lost focus.
    private func appDidActivate(_ bundleID: String?) {
        look()
        if energy.isQuiet {
            frontApps.append(bundleID)
        } else {
            frontApps = [bundleID]
        }
    }

    /// What macOS says comes first, so a change in System Settings takes effect with the next copy.
    /// Returns what became of reading.
    private func keepCopy(_ count: Int, from sources: [String?]) -> Access {
        let answer = system.access(pasteboard)
        guard answer == .allowed else { return answer }
        guard Self.mayRead(pasteboard.types), !sources.contains(where: Self.isPasswordManager) else { return answer }
        guard let text = system.read(pasteboard) else { return .refused }
        // Apps write a copy's types one at a time, and another copy may have landed during the read.
        // What was read is only known to be fine if nothing moved. If it did, the next look deals with it.
        guard system.changeCount(pasteboard) == count, Self.mayRead(pasteboard.types), Self.isKeepable(text) else { return answer }
        withAnimation(.spring(response: 0.35, dampingFraction: 0.8)) {
            if let index = clips.firstIndex(where: { $0.text == text }) {
                bringForward(at: index)
            } else {
                clips.append(Clip(text: text))
                arrange()
            }
        }
        return answer
    }

    /// A plain string, and nothing that says to leave it. Finder puts a file's name on the clipboard
    /// as a string too, and pasting that back would be wrong. `types` covers every item on the
    /// pasteboard, so a concealed second item counts.
    private static func mayRead(_ types: [NSPasteboard.PasteboardType]?) -> Bool {
        let types = Set(types ?? [])
        return types.contains(.string) && !types.contains(.fileURL) && types.isDisjoint(with: skippedTypes)
    }

    /// Short enough, checked first as it costs the least, and more than whitespace.
    private static func isKeepable(_ text: String) -> Bool {
        text.utf16.count <= longest && text.contains { !$0.isWhitespace }
    }

    static func isPasswordManager(_ bundleID: String?) -> Bool {
        guard let id = bundleID?.lowercased() else { return false }
        return passwordManagers.contains { id.hasPrefix($0) }
    }

    // MARK: Clips

    /// Pinned first, then newest, with every word of `search` in them.
    func clips(matching search: String) -> [Clip] {
        let words = search.split(whereSeparator: \.isWhitespace)
        guard !words.isEmpty else { return clips }
        return clips.filter { clip in words.allSatisfy { clip.text.localizedCaseInsensitiveContains($0) } }
    }

    /// Puts the clip back on the clipboard and to the front, as copying it again would. The notice
    /// doesn't repeat the text.
    func copy(_ clip: Clip) {
        pasteboard.clearContents()
        pasteboard.setString(clip.text, forType: .string)
        // Not a new copy to look at.
        if isWatching { seenCount = system.changeCount(pasteboard) }
        if let index = clips.firstIndex(where: { $0.id == clip.id }) {
            withAnimation(.spring(response: 0.35, dampingFraction: 0.8)) { bringForward(at: index) }
        }
        LiveActivityCenter.shared.post(LiveNotice(key: "copied", symbol: "doc.on.clipboard.fill", tint: .white,
                                                  text: "Copied"), for: 1.6)
    }

    func togglePin(_ clip: Clip) {
        guard let index = clips.firstIndex(where: { $0.id == clip.id }) else { return }
        withAnimation(.spring(response: 0.35, dampingFraction: 0.8)) {
            clips[index].isPinned.toggle()
            // With the history off only pins are kept, so a clip that stops being one goes.
            if !isWatching, !clips[index].isPinned { clips.remove(at: index) }
            arrange()
        }
        save()
    }

    func remove(_ clip: Clip) {
        guard let index = clips.firstIndex(where: { $0.id == clip.id }) else { return }
        let wasPinned = clips[index].isPinned
        _ = withAnimation(.spring(response: 0.3, dampingFraction: 0.85)) { clips.remove(at: index) }
        if wasPinned { save() }
    }

    /// Forgets everything but what's pinned. What's on the clipboard itself stays.
    func clear() {
        guard clips.contains(where: { !$0.isPinned }) else { return }
        withAnimation(.spring(response: 0.3, dampingFraction: 0.85)) { clips.removeAll { !$0.isPinned } }
    }

    /// The pane in System Settings where Dynotch is listed once macOS has asked about it. On a macOS
    /// that doesn't know this anchor, it opens at the top of Privacy & Security.
    static func openPrivacySettings() {
        CalendarService.openPrivacySettings("Privacy_Pasteboard")
    }

    private func bringForward(at index: Int) {
        let isPinned = clips[index].isPinned
        clips[index].copiedAt = .now
        arrange()
        if isPinned { save() }
    }

    /// Puts pins first, then the newest, and lets go of the oldest beyond the limit. Pins don't count,
    /// so one that's unpinned can be what takes the rest over it.
    private func arrange() {
        clips.sort { $0.isPinned != $1.isPinned ? $0.isPinned : $0.copiedAt > $1.copiedAt }
        let keeping = clips.filter(\.isPinned).count + Self.limit
        if clips.count > keeping { clips.removeLast(clips.count - keeping) }
    }

    // MARK: On disk

    /// Anything can edit the file, so whatever's in it is a pin, and only if it could have been kept.
    private func load() {
        guard let data = try? Data(contentsOf: fileURL), let saved = try? JSONDecoder().decode([Clip].self, from: data) else { return }
        clips = saved.filter { Self.isKeepable($0.text) }.map { clip in
            var clip = clip
            clip.isPinned = true
            return clip
        }
        arrange()
    }

    /// Only ever the pins, and no file at all once there are none.
    private func save() {
        let pins = clips.filter(\.isPinned)
        guard !pins.isEmpty else {
            try? FileManager.default.removeItem(at: fileURL)
            return
        }
        guard let data = try? JSONEncoder().encode(pins) else { return }
        try? FileManager.default.createDirectory(at: support, withIntermediateDirectories: true)
        write(data)
    }

    /// Owner-only from the first byte. `Data.write` makes the file readable by everyone, and a chmod
    /// afterwards leaves a moment when it is.
    private func write(_ data: Data) {
        let draft = support.appendingPathComponent(".clipboard-\(UUID().uuidString).json")
        let descriptor = open(draft.path, O_WRONLY | O_CREAT | O_EXCL, 0o600)
        guard descriptor >= 0 else { return }
        let handle = FileHandle(fileDescriptor: descriptor, closeOnDealloc: true)
        do {
            try handle.write(contentsOf: data)
            try handle.close()
            if rename(draft.path, fileURL.path) != 0 { try FileManager.default.removeItem(at: draft) }
        } catch {
            try? FileManager.default.removeItem(at: draft)
        }
    }

    // MARK: Snapshots

    /// Made-up clips, in the order they'd show. Nothing is saved.
    func loadSample(_ samples: [Clip], access: Access = .allowed) {
        clips = samples
        self.access = access
    }
}

extension ClipboardStore.Access {
    /// What macOS says about reading this pasteboard. It can change at any time from System Settings.
    /// Before macOS 15.4 nothing stands in the way.
    init(of pasteboard: NSPasteboard) {
        guard #available(macOS 15.4, *) else {
            self = .allowed
            return
        }
        switch pasteboard.accessBehavior {
        // In `.default` the first read may bring up macOS's alert, which is fair: the user just turned this on.
        case .default, .alwaysAllow: self = .allowed
        case .ask: self = .asks
        case .alwaysDeny: self = .denied
        // Whatever it turns out to mean, it isn't a yes.
        @unknown default: self = .denied
        }
    }

    /// Why nothing new is arriving, for the Clipboard side and Settings.
    var problem: String? {
        switch self {
        case .allowed: nil
        case .asks: "macOS asks before every read, so Dynotch has stopped looking."
        case .denied: "macOS isn't letting Dynotch read the clipboard."
        case .refused: "macOS wouldn't hand over the last copy."
        }
    }
}

extension ClipboardStore.Clip: Codable {
    /// All that's saved. The rest comes from the text.
    private enum CodingKeys: String, CodingKey {
        case id, text, copiedAt, isPinned
    }

    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        try self.init(id: container.decode(UUID.self, forKey: .id), text: container.decode(String.self, forKey: .text),
                      copiedAt: container.decode(Date.self, forKey: .copiedAt), isPinned: container.decode(Bool.self, forKey: .isPinned))
    }
}

extension ClipboardStore.Clip {
    /// What VoiceOver calls it.
    var spokenTitle: String {
        switch kind {
        case .text: title
        case .code: "Code: \(title)"
        case .color: "Color \(title)"
        case .link(let url): "Link to \(url.host ?? title)"
        }
    }

    private static func kind(of text: String) -> Kind {
        if let color = hexColor(text) { return color }
        if let url = webLink(text) { return .link(url) }
        return looksLikeCode(text) ? .code : .text
    }

    private static func firstLine(of text: String) -> String {
        let line = text.prefix(81).prefix { !$0.isNewline }
        return line.count > 80 ? String(line.prefix(80)) + "…" : String(line)
    }

    /// `#RGB`, `#RRGGBB` or `#RRGGBBAA`. The # has to be there, or a word like "decade" would be a color.
    private static func hexColor(_ text: String) -> Kind? {
        guard text.utf8.count <= 9, text.first == "#" else { return nil }
        let digits = text.dropFirst()
        guard [3, 6, 8].contains(digits.count), digits.allSatisfy(\.isHexDigit) else { return nil }
        let hex = digits.count == 3 ? String(digits.flatMap { [$0, $0] }) : String(digits)
        guard let value = UInt32(hex, radix: 16) else { return nil }
        let rgba = hex.count == 8 ? value : value << 8 | 0xFF
        func channel(_ shift: UInt32) -> Double { Double((rgba >> shift) & 0xFF) / 255 }
        return .color(red: channel(24), green: channel(16), blue: channel(8), opacity: channel(0))
    }

    /// Only http and https: anything else could open who knows what.
    private static func webLink(_ text: String) -> URL? {
        guard text.utf8.count <= 2048, !text.contains(where: \.isWhitespace), let url = URL(string: text),
              let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https",
              url.host?.isEmpty == false else { return nil }
        return url
    }

    private static let commands: Set<Substring> = [
        "git", "gh", "npm", "npx", "yarn", "pnpm", "bun", "brew", "swift", "xcrun", "python", "python3", "pip", "pip3",
        "node", "docker", "kubectl", "curl", "wget", "ssh", "scp", "sudo", "rm", "cp", "mv", "mkdir", "chmod", "chown",
        "grep", "sed", "awk", "cd", "ls", "cargo", "tar",
    ]

    private static let codeMarks = ["=>", "->", "==", "!=", "&&", "||", "::", "()", "</", "/>", " --"]

    /// Enough to set a command or a bit of code in monospace, going by the first few lines. It leans
    /// toward prose, which looks wrong in monospace, where code in the system font only looks plain.
    private static func looksLikeCode(_ text: String) -> Bool {
        let lines = text.prefix(1000).split(whereSeparator: \.isNewline).prefix(12)
        guard let first = lines.first else { return false }
        let words = first.split(separator: " ")
        if first.hasPrefix("$ ") { return true }
        if words.count > 1, let word = words.first, commands.contains(word), !first.hasSuffix(".") { return true }
        return lines.contains { line in
            line.hasSuffix("{") || line.hasSuffix("}") || line.hasSuffix(";") || codeMarks.contains { line.contains($0) }
                || (lines.count > 1 && (line.hasPrefix("    ") || line.hasPrefix("\t")))
        }
    }
}
